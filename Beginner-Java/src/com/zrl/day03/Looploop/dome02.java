package com.zrl.day03.Looploop;

public class dome02 {
    public static void main(String[] args) {
        for(int i = 1; i<=5 ;i++){
            for (int j = 1; j <= i; j++){
                System.out.print("*");
            }
            System.out.println();
        }
        int a=1;
        for(int b = 1; b<=5 ;b++){
            for (a = 1; a <= b; a++){
                System.out.print("*");
            }
            System.out.println();
        }
    }
}
